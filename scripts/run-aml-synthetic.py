def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--model", default="BAAI/bge-small-zh-v1.5")
    parser.add_argument("--cache", default="./models")
    parser.add_argument("--json", action="store_true")
    parser.add_argument("--hard", action="store_true", help="include the frozen harder cases")
    parser.add_argument("--holdout", action="store_true", help="include the untouched fallback holdout cases")
    args = parser.parse_args()
    embedder = FastEmbedder(args.model, args.cache, 2)
    ranks = []
    categories: dict[str, list[int]] = {}
    failures = []
    with TemporaryDirectory() as directory:
        adapter = AMLAdapter(Path(directory), embedder, 4)
        selected_cases = CASES + HARD_CASES if args.hard else CASES
        if args.holdout:
            selected_cases += HOLDOUT_CASES
        for case_index, (category, query, expected_id, rows) in enumerate(selected_cases):
            user_id = f"synthetic-{case_index}"
            for row_index, (memory_id, content, timestamp) in enumerate(rows):
                adapter.add({"request_id": memory_id, "user_id": user_id, "session_id": f"s-{row_index}",
                             "messages": [{"role": "user", "content": content, "timestamp": timestamp}]})
            result = adapter.search({"query": query, "user_id": user_id, "top_k": len(rows)})["data"]
            expected_content = next(content for memory_id, content, _ in rows if memory_id == expected_id)
            rank = next((index + 1 for index, item in enumerate(result) if item["content"] == expected_content), 0)
            ranks.append(rank)
            categories.setdefault(category, []).append(rank)
            if rank != 1:
                expected_result = next((item for item in result if item["content"] == expected_content), {})
                failures.append({"category": category, "query": query, "rank": rank,
                                 "expected": expected_content,
                                 "expected_score": expected_result.get("score"),
                                 "returned_first": result[0]["content"] if result else None,
                                 "returned_first_score": result[0].get("score") if result else None})
    report = {
        "cases": len(ranks),
        "top_1": sum(rank == 1 for rank in ranks),
        "top_3": sum(0 < rank <= 3 for rank in ranks),
        "mrr": round(sum(1 / rank for rank in ranks if rank) / len(ranks), 4),
        "categories": {name: {"top_1": sum(rank == 1 for rank in values), "cases": len(values)}
                       for name, values in categories.items()},
        "failures": failures,
    }
    print(json.dumps(report, ensure_ascii=False, indent=2) if args.json else report)
    return 0 if report["top_3"] == report["cases"] else 1


if __name__ == "__main__":
    raise SystemExit(main())
